class ProfileModel {
  final String nik;

  final String fullName;

  final String email;

  final String password;

  final String birthDate;

  final bool isMale;

  ProfileModel({
    required this.nik,
    required this.fullName,
    required this.email,
    required this.password,
    required this.birthDate,
    required this.isMale,
  });
}
